"""Exports every Mermaid diagram of the specs as SVG and PNG into specs/architecture/diagrams/.

The Markdown keeps the Mermaid source (diffable, rendered by GitHub); the exported files are for the PDF/DOCX
report and for readers without a Mermaid viewer. Rendering also proves every diagram parses.
Needs Node.js and a Chrome/Chromium (PUPPETEER_EXECUTABLE_PATH). Run:  python tools/render_diagrams.py
"""
from __future__ import annotations

import json
import os
import re
import shutil
import subprocess
import sys
import tempfile
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
OUT = ROOT / "specs/architecture/diagrams"
SOURCES = ["specs/architecture/architecture.md", "specs/domain/domain-model.md", "specs/use-cases/use-cases.md",
           "specs/migration/legacy-mapping.md", "README.md"]


def slug(s: str) -> str:
    return re.sub(r"[^a-z0-9]+", "-", s.lower()).strip("-")[:50]


def blocks(md: Path):
    text = md.read_text(encoding="utf-8")
    heading = md.stem
    for part in re.split(r"(^#{1,3} .*$)", text, flags=re.M):
        if part.startswith("#"):
            heading = part.lstrip("# ").strip()
            continue
        for i, src in enumerate(re.findall(r"```mermaid\n(.*?)```", part, re.S)):
            yield f"{slug(md.stem)}--{slug(heading)}" + (f"-{i + 1}" if i else ""), src


def main() -> int:
    chrome = os.environ.get("PUPPETEER_EXECUTABLE_PATH") or shutil.which("google-chrome") or shutil.which("chromium")
    if not chrome:
        print("No Chrome/Chromium found; set PUPPETEER_EXECUTABLE_PATH")
        return 1
    OUT.mkdir(parents=True, exist_ok=True)
    env = {**os.environ, "PUPPETEER_EXECUTABLE_PATH": chrome, "PUPPETEER_SKIP_DOWNLOAD": "1"}
    failures, index = 0, []
    with tempfile.TemporaryDirectory() as tmp:
        cfg = Path(tmp) / "puppeteer.json"
        cfg.write_text(json.dumps({"args": ["--no-sandbox"]}))
        for rel in SOURCES:
            for name, src in blocks(ROOT / rel):
                mmd = Path(tmp) / f"{name}.mmd"
                mmd.write_text(src, encoding="utf-8")
                for ext in ("svg", "png"):
                    out = OUT / f"{name}.{ext}"
                    cmd = ["npx", "-y", "@mermaid-js/mermaid-cli@11", "-q", "-p", str(cfg), "-i", str(mmd), "-o", str(out),
                           "-b", "white"] + (["-s", "2"] if ext == "png" else [])
                    r = subprocess.run(cmd, capture_output=True, text=True, env=env)
                    if r.returncode != 0:
                        failures += 1
                        print(f"✗ {name}.{ext}: {r.stderr.strip()[-300:]}")
                        break
                else:
                    print(f"✓ {name} ({rel})")
                    index.append((name, rel))
    lines = ["# Diagrams (exported)", "",
             "Generated by `python tools/render_diagrams.py` from the Mermaid sources; edit the source, not these files.", "",
             "| Diagram | Source | SVG | PNG |", "|---|---|---|---|"]
    lines += [f"| {n} | [{Path(s).name}](../../../{s}) | [svg]({n}.svg) | [png]({n}.png) |" for n, s in index]
    (OUT / "README.md").write_text("\n".join(lines) + "\n", encoding="utf-8")
    print(f"{len(index)} diagrams exported, {failures} failed")
    return 1 if failures else 0


if __name__ == "__main__":
    sys.exit(main())
